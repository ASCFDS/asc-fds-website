const assert = require('node:assert/strict');
require('../assets/js/event-model.js');
require('../assets/js/event-calendar.js');
const {calendar,matches}=globalThis.ASCEvents;
const now=new Date('2026-10-04T12:00:00Z');
const base={title:'Ski-Ausfahrt Obersaxen',startDate:'2027-01-08',endDate:'2027-01-10',hasTime:false};
const unfold=s=>s.replace(/\r\n /g,'');
const ics=calendar(base,now);
assert(ics.includes('DTSTART;VALUE=DATE:20270108\r\n'));
assert(ics.includes('DTEND;VALUE=DATE:20270111\r\n'));
assert(!ics.includes('LOCATION:'));
assert(!ics.includes('RRULE:'));
assert(ics.endsWith('END:VCALENDAR\r\n'));
assert(calendar({...base,startDate:'2028-02-29',endDate:'2028-02-29'},now).includes('DTEND;VALUE=DATE:20280301'));
assert(calendar({...base,startDate:'2026-12-31',endDate:'2026-12-31'},now).includes('DTEND;VALUE=DATE:20270101'));
const timed=calendar({...base,hasTime:true,startDate:'2026-10-25T02:30:00+02:00',endDate:'2026-10-25T02:30:00+01:00'},now);
assert(timed.includes('DTSTART:20261025T003000Z'));assert(timed.includes('DTEND:20261025T013000Z'));
assert(!calendar({...base,hasTime:true,endDate:base.startDate},now).includes('DTEND'));
const malicious=calendar({...base,title:'Ä'.repeat(100)+' 🎯',description:'Text, neu; \\ Wort\r\nBEGIN:VEVENT',location:'Ort; Halle'},now);
for(const line of malicious.split('\r\n'))assert(Buffer.byteLength(line)<=75);
const plain=unfold(malicious);assert(plain.includes('SUMMARY:'+'Ä'.repeat(100)+' 🎯'));assert(plain.includes('DESCRIPTION:Text\\, neu\\; \\\\ Wort\\nBEGIN:VEVENT'));assert.equal(malicious.split('\r\nBEGIN:VEVENT').length,2);
const uid=s=>unfold(s).match(/UID:(.*)\r\n/)[1];assert.equal(uid(ics),uid(calendar({...base,description:'Changed'},new Date('2026-10-05'))));
for(const blocked of [{visibility:'private'},{cancelled:true},{publishToHomepage:false},{startDate:'invalid'}])assert.throws(()=>calendar({...base,...blocked}));
assert(matches('schuetzen 2027',['Schützenhaus','2027']));assert(matches('pärnu',['Pärnu']));assert(!matches('ski 2026',['Ski 2027']));
console.log('PASS: calendar dates, leap/year boundaries, DST, no invented duration/location, stable UID, UTF-8 folding, escaping, private-event rejection, search.');
